let searchBarre = false;

//gere la barre de recherche
if (searchBtn) {
    searchBtn.addEventListener('click', (e) => {
        if (window.innerWidth >= 850) {
            searchBarre = false;
            searchBtn.classList.remove('mobile-active');
            return;
        }

        if (!searchBarre) {
            searchBarre = true;
            searchBtn.classList.add('mobile-active');
            
            setTimeout(() => {
                const input = searchBtn.querySelector('input');
                if (input) input.focus();
            }, 100);
        } 
        else {
            const clickedCross = e.target.closest('#close-search');
            
            if (clickedCross) {
                searchBarre = false;
                searchBtn.classList.remove('mobile-active');
                researchMenu.remove();
            }
        }
    });
}

//gere la communication avec l'API de recherche quand on écrit dans l'input
if (searchInput) {
    let timeoutId;

    searchInput.addEventListener('input', (e) => {
        const text = e.target.value.trim();

        clearTimeout(timeoutId);

        if (text.length === 0) {
            return;
        }


        timeoutId = setTimeout(() => {
            
            fetch(`../MSmangaT/API/search.php?search=${encodeURIComponent(text)}`)
                .then(response => {
                    if (!response.ok) throw new Error('Erreur réseau');
                    return response.json();
                })
                .then(resultData => {
                    if (resultData.success) {
                        const mangaIds = resultData.data;

                        let researchMenu = document.getElementById('researchMenu');
                        let accountMenu = document.getElementById('accountMenu');
                        
                        if(accountMenu){
                            accountMenu.remove();
                        }

                        if (!researchMenu) {
                            researchMenu = document.createElement('div');
                            researchMenu.id = 'researchMenu';
                            
                            document.body.appendChild(researchMenu);
                            
                            researchMenu.innerHTML =  `<hr class="ligne"></hr>
                            
                            `;

                        } else {
                            researchMenu.remove();
                        }

                        mangaIds.forEach((mangaId) =>  {
                            fetch(`../MSmangaT/API/getImageAndNameById.php?id=${encodeURIComponent(mangaId)}`)
                                .then(response => {
                                    if (!response.ok) throw new Error('Erreur réseau');
                                    return response.json();
                                })
                                .then(resultData => {
                                    if (resultData.success) {
                                        const mangaInfo = resultData.data;

                                        researchMenu.innerHTML += `
                                            <a href="manga?id=${mangaId}" class="search-result-item">
                                                <img class="manga-cover-search" src="${mangaInfo['chemin_image']}" alt="Couverture de ${mangaInfo['titre']}" />
                                                <span>${mangaInfo['titre']}</span>
                                            </a>
                                            <hr class="ligne"></hr>
                                        `;
                                    }
                                })
                                .catch(error => {
                                    console.error('Erreur lors de la recherche:', error);
                                });
                        });
                    }
                })
                .catch(error => {
                    console.error('Erreur lors de la recherche:', error);
                });

        if (researchMenu && researchMenu.innerHTML === `<hr class="ligne"></hr>`){
            researchMenu.remove();
            return;
        }

        }, 700);
    });
}


